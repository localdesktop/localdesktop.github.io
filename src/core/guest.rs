/// UI scale derived from the Android density: `density / 160 * 1.1`, rounded to the nearest
/// 0.25, at least 1.0. Same rule the compositor uses for the host side of the output contract.
pub fn auto_ui_scale(density_dpi: i32) -> f32 {
    ((density_dpi as f32 / 160.0 * 1.1) * 4.0).round().max(4.0) / 4.0
}

/// The UI scale in effect: the configured `ui_scale` when positive, the automatic one otherwise.
pub fn effective_ui_scale(display: &DisplayConfig, density_dpi: i32) -> f32 {
    if display.ui_scale > 0.0 {
        display.ui_scale
    } else {
        auto_ui_scale(density_dpi)
    }
}

/// Plain integer DPI for xfconf's `/Xft/DPI` (96 at scale 1). xfsettingsd multiplies by 1024
/// itself when it publishes the XSETTINGS value to X clients.
pub fn xft_dpi(scale: f32) -> i32 {
    (scale * 96.0).round() as i32
}

