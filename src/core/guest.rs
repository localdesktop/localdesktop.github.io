/// `/etc/localdesktop/session-env.sh`: performance and GPU environment sourced by
/// `startxfce4-localdesktop` before the desktop starts. Regenerated on every app start, so the
/// result always follows `localdesktop.toml`.
pub fn session_env(config: &LocalConfig, cpus: usize) -> String {
    let mut env = String::from(
        "# Generated by Local Desktop on every start from /etc/localdesktop/localdesktop.toml.\n\
# Do not edit: put your own overrides in /etc/localdesktop/session-env.local instead.\n",
    );
    env.push_str(&format!(
        "\n# llvmpipe (software OpenGL) worker threads: one per CPU.\nexport LP_NUM_THREADS={}\n",
        cpus.max(1)
    ));

    const SOFTWARE_RENDERING: &str = "\
# GTK 4 draws through the OpenGL renderer by default, which is slow on llvmpipe.
export GSK_RENDERER=cairo
# Skip driver probing: llvmpipe is the only OpenGL implementation without the GPU option.
export LIBGL_ALWAYS_SOFTWARE=1
# labwc has no GPU buffers to render with, so wlroots uses its CPU (pixman) renderer.
export WLR_RENDERER=pixman
";

    if config.gpu.enabled {
        env.push_str(&format!(
            "\n# [gpu] enabled = true: Mesa KGSL build in {prefix}, once its installation has finished.\n\
if [ -r {gpu_env} ] && [ -e {prefix}/.release ]; then\n    . {gpu_env}\nelse\n",
            prefix = MESA_KGSL_PREFIX,
            gpu_env = GPU_ENV_PATH,
        ));
        for line in SOFTWARE_RENDERING.lines() {
            env.push_str("    ");
            env.push_str(line);
            env.push('\n');
        }
        env.push_str("fi\n");
    } else {
        env.push('\n');
        env.push_str(SOFTWARE_RENDERING);
    }

    if config.x86.wine {
        env.push_str(
            "\n# Wine under Box64 in proot: no futex/eventfd semantics for esync/fsync.\n\
export WINEESYNC=0\nexport WINEFSYNC=0\n",
        );
    }
    env
}

/// `/etc/localdesktop/gpu-env.sh`: the KGSL Mesa environment for `[gpu] enabled = true`.
pub fn gpu_env(gpu: &GpuConfig) -> String {
    let zink = gpu.driver.trim().eq_ignore_ascii_case("zink");
    let mut env = format!(
        "# Generated by Local Desktop: environment for the experimental Adreno GPU path.\n\
# Mesa {release} (lfdevs/mesa-for-android-container) with the KGSL backend lives in a separate\n\
# prefix; this file is only sourced while [gpu] enabled = true, so the stock Mesa returns when it is off.\n\
prefix={prefix}\n\
export LD_LIBRARY_PATH=\"$prefix/usr/lib${{LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}}\"\n\
export LIBGL_DRIVERS_PATH=\"$prefix/usr/lib/dri\"\n\
export GBM_BACKENDS_PATH=\"$prefix/usr/lib/gbm\"\n\
export __EGL_VENDOR_LIBRARY_FILENAMES=\"$prefix/usr/share/glvnd/egl_vendor.d/50_mesa.json\"\n\
export DRIRC_CONFIGDIR=\"$prefix/usr/share/drirc.d\"\n\
export VK_ICD_FILENAMES=\"$prefix/usr/share/vulkan/icd.d/freedreno_icd.aarch64.json\"\n\
export VK_DRIVER_FILES=\"$VK_ICD_FILENAMES\"\n",
        release = crate::core::config::MESA_KGSL_RELEASE,
        prefix = MESA_KGSL_PREFIX,
    );

    if zink {
        env.push_str(
            "\n# [gpu] driver = \"zink\": OpenGL through Zink on the Turnip Vulkan driver.\n\
export MESA_LOADER_DRIVER_OVERRIDE=zink\n\
export GALLIUM_DRIVER=zink\n\
export ZINK_CONTEXT_THREADED=1\n",
        );
    } else {
        env.push_str(
            "\n# [gpu] driver = \"freedreno\": OpenGL/GLES directly on Freedreno over KGSL.\n\
export MESA_LOADER_DRIVER_OVERRIDE=kgsl\n",
        );
    }

    env.push_str(
        "\n# Turnip on Adreno 8xx needs LRZ off (GameNative uses the same workaround). The model is\n\
# read from KGSL; when it cannot be read the flag is set, as this build targets Adreno 8xx.\n\
gpu_model=\"\"\n\
{ read -r gpu_model; } 2>/dev/null < /sys/class/kgsl/kgsl-3d0/gpu_model\n\
case \"$gpu_model\" in\n\
    Adreno[0-7]*) ;;\n\
    *) export TU_DEBUG=\"${TU_DEBUG:+$TU_DEBUG,}nolrz\" ;;\n\
esac\n\
unset gpu_model\n\
\n\
# Present path. With a zwp_linux_dmabuf_v1 global on the host compositor, buffers are shared\n\
# zero-copy and labwc may render with GLES. Without it clients render on the GPU but hand frames\n\
# over through wl_shm (one copy), and labwc stays on the CPU renderer.\n\
if command -v wayland-info >/dev/null 2>&1 &&\n\
    WAYLAND_DISPLAY=\"${WAYLAND_DISPLAY:-wayland-0}\" XDG_RUNTIME_DIR=\"${XDG_RUNTIME_DIR:-/tmp}\" \\\n\
        timeout 5 wayland-info 2>/dev/null | grep -q zwp_linux_dmabuf_v1; then\n\
    export WLR_RENDERER=gles2\n\
else\n\
    export WLR_RENDERER=pixman\n\
    export LIBGL_KOPPER_DISABLE=true\n\
    export MESA_VK_WSI_DEBUG=sw\n\
fi\n",
    );
    env
}

/// Managed `/etc/pacman.d/mirrorlist`: HTTPS mirrors only.
pub fn managed_mirrorlist() -> String {
    let mut list = String::from(
        "# Arch Linux ARM mirrors over HTTPS. Written once by Local Desktop because the original\n\
# list used plain HTTP; it is only rewritten again if plain-HTTP servers show up in it.\n\
# (The geo-redirector mirror.archlinuxarm.org has no valid TLS certificate, so it is not used.)\n\n",
    );
    for mirror in PACMAN_MIRRORS {
        list.push_str("Server = ");
        list.push_str(mirror);
        list.push('\n');
    }
    list
}

/// `true` when an active (uncommented) `Server` line of the mirror list uses plain HTTP.
pub fn mirrorlist_has_plain_http(content: &str) -> bool {
    content.lines().any(|line| {
        let line = line.trim();
        !line.starts_with('#')
            && line
                .split_once('=')
                .map_or(false, |(key, value)| {
                    key.trim() == "Server" && value.trim().starts_with("http://")
                })
    })
}

const MAKEFLAGS_LINE: &str = "MAKEFLAGS=\"-j$(nproc)\" # Local Desktop: build with every CPU";

/// Enables parallel builds in `makepkg.conf`. A commented-out `MAKEFLAGS` is replaced, a missing
/// one is appended, an active one (set by the user or by us before) is left alone.
/// `None` when nothing has to change.
pub fn ensure_makeflags(content: &str) -> Option<String> {
    let is_assignment = |line: &str, commented: bool| {
        let line = line.trim_start();
        let line = if commented {
            match line.strip_prefix('#') {
                Some(rest) => rest.trim_start(),
                None => return false,
            }
        } else {
            line
        };
        line.starts_with("MAKEFLAGS=")
    };

    if content.lines().any(|line| is_assignment(line, false)) {
        return None;
    }

    let mut replaced = false;
    let mut out = String::with_capacity(content.len() + MAKEFLAGS_LINE.len() + 1);
    for line in content.lines() {
        if !replaced && is_assignment(line, true) {
            out.push_str(MAKEFLAGS_LINE);
            replaced = true;
        } else {
            out.push_str(line);
        }
        out.push('\n');
    }
    if !replaced {
        out.push_str(MAKEFLAGS_LINE);
        out.push('\n');
    }
    Some(out)
}

/// Firefox autoconfig (`localdesktop.cfg`). The first line has to be a comment.
/// The sandbox preferences are required by proot; the rendering preferences target CPU-only
/// rendering and are skipped when the GPU option is on.
pub fn firefox_autoconfig(gpu_enabled: bool) -> String {
    let mut cfg = String::from(
        r#"// Auto updated by Local Desktop on each startup, do not edit manually
defaultPref("media.cubeb.sandbox", false);
defaultPref("security.sandbox.content.level", 0);
defaultPref("media.allow-audio-non-utility", true);
defaultPref("media.rdd-process.enabled", false);
// Fewer content processes and rarer session-store writes: proot counts every process.
defaultPref("dom.ipc.processCount", 4);
defaultPref("browser.sessionstore.interval", 60000);
"#,
    );
    if !gpu_enabled {
        cfg.push_str(
            r#"// CPU-only rendering: WebRender's software backend instead of OpenGL on llvmpipe.
defaultPref("gfx.webrender.software", true);
defaultPref("media.hardware-video-decoding.enabled", false);
"#,
        );
    }
    cfg.push_str(
        r#"
try {
  var { SandboxUtils } = ChromeUtils.importESModule("resource://gre/modules/SandboxUtils.sys.mjs");
  SandboxUtils.maybeWarnAboutDisabledContentSandbox = () => {};
  SandboxUtils.observeContentSandboxPref = () => {};
} catch (_) {}
"#,
    );
    cfg // It is required that the first line of this file is a comment. Docs: https://support.mozilla.org/en-US/kb/customizing-firefox-using-autoconfig
}

